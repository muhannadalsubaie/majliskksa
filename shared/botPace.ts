// سرعة الروبوت مثل اللاعب الحقيقي: وقت تفكير طبيعي يختلف حسب القرار —
// «بس» أسرع من الشراء، والورقة الوحيدة المسموحة أسرع من الاختيار بين أوراق كثيرة،
// وبداية الأكلة تاخذ تفكير أكثر، وآخر الصكة أسرع. التوزيع مائل للوسط (مثل البشر) لا عشوائي بحت.
export type Rng = () => number;

/** وقت بين min و max، أغلبه حول الوسط */
export function human(rng: Rng, min: number, max: number): number {
  const r = (rng() + rng()) / 2;
  return Math.round(min + (max - min) * r);
}
